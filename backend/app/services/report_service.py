import json
from typing import Optional, List
from sqlalchemy.orm import Session
from sqlalchemy import desc

from app.models.report import Report
from app.models.engagement import Engagement
from app.models.client import Client
from app.models.asset import Asset
from app.models.finding import Finding
from app.models.user import User
from app.schemas.report import ReportCreate
from app.services.audit_service import log_audit


def generate_report(db: Session, report_in: ReportCreate, current_user: User) -> Report:
    eng_q = db.query(Engagement).filter(Engagement.id == report_in.engagement_id)
    if current_user.organization_id:
        eng_q = eng_q.filter(Engagement.organization_id == current_user.organization_id)
    engagement = eng_q.first()
    if not engagement:
        raise ValueError("Referenced engagement does not exist.")

    client = db.query(Client).filter(Client.id == engagement.client_id).first()
    assets = db.query(Asset).filter(Asset.engagement_id == engagement.id).all()
    findings = (
        db.query(Finding)
        .filter(Finding.engagement_id == engagement.id)
        .order_by(Finding.severity)
        .all()
    )

    # Calculate real metrics
    severity_counts = {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
    status_counts = {"open": 0, "in_remediation": 0, "verified_fixed": 0, "accepted_risk": 0}

    findings_data = []
    for f in findings:
        severity_counts[f.severity] = severity_counts.get(f.severity, 0) + 1
        status_counts[f.status] = status_counts.get(f.status, 0) + 1
        findings_data.append({
            "id": f.id,
            "title": f.title,
            "severity": f.severity,
            "cvss_score": f.cvss_score,
            "status": f.status,
            "cve_id": f.cve_id,
            "description": f.description,
            "impact": f.impact,
            "remediation_guidance": f.remediation_guidance,
            "asset_name": f.asset.name if f.asset else "Unassigned",
        })

    metrics = {
        "total_findings": len(findings),
        "total_assets": len(assets),
        "severity_breakdown": severity_counts,
        "status_breakdown": status_counts,
    }

    # Generate professional Markdown summary
    summary = f"""# Executive Cybersecurity Assessment Report
**Engagement**: {engagement.name}  
**Client Organization**: {client.company_name if client else 'N/A'}  
**Assessment Type**: {engagement.assessment_type.replace('_', ' ').title()}  
**Report Type**: {report_in.report_type.replace('_', ' ').title()}  
**Generated By**: {current_user.full_name} ({current_user.email})  

---

## 1. Executive Summary
This report summarizes the findings, risk posture, and remediation actions performed during the **{engagement.name}** assessment for **{client.company_name if client else 'Client'}**. 
A total of **{len(findings)}** vulnerabilities were identified across **{len(assets)}** authorized in-scope assets.

### Risk Overview
- **Critical Severity**: {severity_counts['critical']}
- **High Severity**: {severity_counts['high']}
- **Medium Severity**: {severity_counts['medium']}
- **Low Severity**: {severity_counts['low']}
- **Informational**: {severity_counts['info']}

---

## 2. Scope & Target Assets
The assessment scope was strictly limited to approved digital assets:
"""
    for a in assets:
        summary += f"- **{a.name}** (`{a.target}`) - Environment: *{a.environment}*, Criticality: *{a.criticality}*\n"

    if not assets:
        summary += "_No specific assets were linked to this engagement record._\n"

    summary += f"""
---

## 3. Discovered Vulnerabilities & Remediation
"""
    for f in findings:
        summary += f"""### [{f.severity.upper()}] {f.title}
- **Status**: `{f.status}`
- **CVE Reference**: {f.cve_id or 'N/A'}
- **CVSS Score**: {f.cvss_score or 'N/A'}
- **Impact**: {f.impact or 'Risk exposure upon unauthorized exploitation.'}
- **Remediation Recommendation**: {f.remediation_guidance or 'Apply latest security patches and adhere to least-privilege configurations.'}

"""

    report = Report(
        engagement_id=engagement.id,
        title=report_in.title,
        report_type=report_in.report_type,
        status="generated",
        summary_content=report_in.summary_content or summary,
        findings_snapshot=json.dumps(findings_data),
        metrics_snapshot=json.dumps(metrics),
        generated_by=current_user.email,
    )
    db.add(report)
    db.commit()
    db.refresh(report)

    log_audit(
        db=db,
        organization_id=current_user.organization_id,
        user_email=current_user.email,
        action="GENERATE_REPORT",
        resource_type="report",
        resource_id=report.id,
        details=f"Generated {report.report_type} report '{report.title}' for engagement '{engagement.name}'",
    )
    return report


def get_report_by_id(
    db: Session, report_id: str, organization_id: Optional[str] = None
) -> Optional[Report]:
    query = db.query(Report).filter(Report.id == report_id)
    if organization_id:
        query = query.join(Engagement, Report.engagement_id == Engagement.id).filter(
            Engagement.organization_id == organization_id
        )
    return query.first()


def get_reports(
    db: Session,
    organization_id: Optional[str] = None,
    engagement_id: Optional[str] = None,
    report_type: Optional[str] = None,
    client_id: Optional[str] = None,
    page: int = 1,
    page_size: int = 50,
) -> tuple[List[Report], int]:
    query = db.query(Report)
    if organization_id or client_id:
        query = query.join(Engagement, Report.engagement_id == Engagement.id)
        if organization_id:
            query = query.filter(Engagement.organization_id == organization_id)
        if client_id:
            query = query.filter(Engagement.client_id == client_id)
    if engagement_id:
        query = query.filter(Report.engagement_id == engagement_id)
    if report_type:
        query = query.filter(Report.report_type == report_type)

    total = query.count()
    items = (
        query.order_by(desc(Report.created_at))
        .offset((page - 1) * page_size)
        .limit(page_size)
        .all()
    )
    return items, total
